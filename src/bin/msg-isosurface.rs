use std::{
    fs::File,
    io::{BufWriter, Write},
    path::{Path, PathBuf},
    time::Instant,
};

use anyhow::{Context, Result, ensure};
use clap::Parser;
use multires_rs::{
    IsosurfaceOptions, MappedMsgArchive, Mesh3D, Sample, Surface, isosurface_archive,
};

#[derive(Debug, Parser)]
#[command(about = "Extract an MC33 isosurface from a point-based MSG field")]
struct Args {
    input: PathBuf,
    field: String,
    #[arg(allow_hyphen_values = true)]
    isovalue: f64,
    output: PathBuf,
    #[arg(
        long = "sample",
        value_names = ["FIELD", "MIN", "MAX"],
        num_args = 3,
        action = clap::ArgAction::Append,
        allow_hyphen_values = true
    )]
    sample_values: Vec<String>,
    #[arg(long)]
    flip_winding: bool,
}

fn main() -> Result<()> {
    let args = Args::parse();
    ensure!(
        args.sample_values.len() <= 6,
        "--sample may be specified at most twice"
    );
    let sampled_quantities = args
        .sample_values
        .chunks_exact(3)
        .map(|values| {
            let min = values[1]
                .parse::<f64>()
                .with_context(|| format!("invalid sample minimum {:?}", values[1]))?;
            let max = values[2]
                .parse::<f64>()
                .with_context(|| format!("invalid sample maximum {:?}", values[2]))?;
            Ok(Sample {
                field: values[0].clone(),
                range: min..=max,
            })
        })
        .collect::<Result<Vec<_>>>()?;
    let load_start = Instant::now();
    let mapped = MappedMsgArchive::open(&args.input)?;
    let archive = mapped.view()?;
    let load_time = load_start.elapsed();
    let extraction_start = Instant::now();
    let (mesh, timings) = isosurface_archive(
        &archive,
        IsosurfaceOptions {
            surface: Surface {
                field: args.field,
                value: args.isovalue,
            },
            sampled_quantities,
            levels: None,
            flip_winding: args.flip_winding,
        },
    )?;
    let extraction_time = extraction_start.elapsed();
    write_obj(&args.output, &mesh, !args.sample_values.is_empty())?;
    eprintln!(
        "wrote {} vertices and {} faces to {}",
        mesh.positions.len(),
        mesh.indices.len(),
        args.output.display()
    );
    eprintln!(
        "timings: load {:.6}s, preparation {:.6}s, extraction {:.6}s",
        load_time.as_secs_f64(),
        timings.preparation.as_secs_f64(),
        extraction_time.as_secs_f64()
    );
    for (index, level) in timings.per_level.iter().enumerate() {
        eprintln!(
            "  level {index}: mesh {:.6}s, merge {:.6}s, winding {:.6}s",
            level.mesh_generation_time.as_secs_f64(),
            level.merge_time.as_secs_f64(),
            level.winding_time.as_secs_f64()
        );
    }
    Ok(())
}

fn write_obj(path: &Path, mesh: &Mesh3D, write_uvs: bool) -> Result<()> {
    let mut output =
        BufWriter::new(File::create(path).with_context(|| format!("creating {}", path.display()))?);
    writeln!(output, "# generated by msg-isosurface")?;
    for position in &mesh.positions {
        writeln!(output, "v {} {} {}", position[0], position[1], position[2])?;
    }
    if write_uvs {
        for uv in &mesh.uv {
            writeln!(output, "vt {} {}", uv[0], uv[1])?;
        }
    }
    for face in &mesh.indices {
        let indices = face.map(|index| u64::from(index) + 1);
        if write_uvs {
            writeln!(
                output,
                "f {0}/{0} {1}/{1} {2}/{2}",
                indices[0], indices[1], indices[2]
            )?;
        } else {
            writeln!(output, "f {} {} {}", indices[0], indices[1], indices[2])?;
        }
    }
    output.flush()?;
    Ok(())
}
